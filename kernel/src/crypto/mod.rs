//!
//! # 暗号プリミティブモジュール
//!
//! ExoRust カーネル全体で使用されるハッシュ関数・署名検証などの
//! 暗号プリミティブを集約するモジュール。
//!
//! ## モジュール構成
//! - [`sha256`] — SHA-256 ハッシュ (FIPS 180-4)
//! - [`sha384`] — SHA-384 ハッシュ (FIPS 180-4)
//! - [`sha512`] — SHA-512 ハッシュ (FIPS 180-4)
//! - [`ed25519`] — Ed25519 署名検証 (RFC 8032)
//!
//! ## 設計経緯
//!
//! これらのプリミティブは当初 `loader/` モジュール内に配置されていたが、
//! TLS (HKDF, HMAC)、セル署名検証、ネットワークセキュリティなど
//! 複数のサブシステムから横断的に使用されるため、独立モジュールに分離した。
//!
//! ## 利用箇所
//! - `loader/signature.rs` — セルの署名検証
//! - `loader/driver_pack.rs` — ドライバパックのハッシュ検証
//! - `net/security/tls/crypto/hmac.rs` — HMAC-SHA256/384
//! - `net/security/tls/crypto/hkdf.rs` — HKDF 鍵導出

pub mod ed25519;
pub mod sha256;
pub mod sha384;
pub mod sha512;
